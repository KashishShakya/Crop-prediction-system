import pandas as pd
from sklearn.model_selection import train_test_split
from sklearn.ensemble import RandomForestClassifier
import pickle

data=pd.read_csv('Crop_recommendation.csv')

data.head()

data.shape

data.isnull().sum()

#split features and label

x= data.iloc[:, :-1] #all col except last
y=data.iloc[:,-1] #bacha hua (last) col

x_train, x_test, y_train, y_test = train_test_split(x, y, test_size=0.2, random_state=42) #random state mtlb bar bar train test krne se same split bane

model=RandomForestClassifier()

model.fit(x_train, y_train)

pickle.dump(model, open("model.pkl", "wb"))

predictions=model.predict(x_test)

accuracy = model.score(x_test, y_test)
print("Accuracy:", accuracy)

new_features = [[36, 58, 25, 28.66024, 59.31891, 8.399136, 36.9263]]
predictions = model.predict(new_features)
print("Predicted Crop:", predictions[0])

